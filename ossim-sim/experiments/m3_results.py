"""Regenerates docs/m3_results.md and docs/figures/m3_fifo_vs_lru.png from the engine (no hand-typed numbers).

Run from ossim-sim:  python experiments/m3_results.py      (the figure needs matplotlib; the tables do not)
"""
from pathlib import Path

from ossim.managers.file import FileManager
from ossim.managers.memory import MemoryManager

ROOT = Path(__file__).resolve().parent.parent
TRACES = [("Baseline trace (10 references)", "inputs/trace_baseline.txt"), ("Locality trace (20 references)", "inputs/trace_locality.txt")]


def memory_rows():
    rows = []
    for label, path in TRACES:
        for policy in ("fifo", "lru"):
            mm = MemoryManager()
            assert mm.configure({"policy": policy}) == [] and mm.load(str(ROOT / path)) == []
            mm.run()
            m = {k: v["value"] for k, v in mm.metrics().items()}
            rows.append((label, policy.upper(), m))
    return rows


def file_summary(script):
    fm = FileManager()
    assert fm.load(str(ROOT / script)) == []
    fm.run()
    return fm


def main():
    mem = memory_rows()
    out = ["# Milestone 3 results", "", "Generated by `experiments/m3_results.py` from the engine. The same values are checked against hand-worked",
           "numbers in `tests/unit/test_memory_manager.py`, `test_memory_locality.py` and `test_file_manager.py`.", "",
           "## FIFO vs LRU on identical traces (4096-byte pages, 3 frames, hit 0.1 ms, fault 5.0 ms)", "",
           "| Trace | Policy | References | Hits | Faults | Evictions | Fault rate (%) | Hit rate (%) | Avg access (ms) |", "| --- | --- | --- | --- | --- | --- | --- | --- | --- |"]
    for label, pol, m in mem:
        out.append(f"| {label} | {pol} | {m['references']} | {m['hits']} | {m['faults']} | {m['evictions']} | {m['fault_rate']:.2f} | {m['hit_rate']:.2f} | {m['avg_access_time']:.3f} |")
    out += ["", "![FIFO vs LRU](figures/m3_fifo_vs_lru.png)", "",
            "On the locality trace pages 0 and 1 are re-used constantly. LRU keeps them resident and never evicts them; FIFO evicts them just because they",
            "were loaded first, so it faults 12 times to LRU's 8. On the baseline trace the policies differ by one fault.", ""]
    for title, script in (("12-command baseline script (`inputs/fs_baseline.txt`)", "inputs/fs_baseline.txt"), ("20-command script (`inputs/fs_script.txt`)", "inputs/fs_script.txt")):
        fm = file_summary(script)
        m = {k: v["value"] for k, v in fm.metrics().items()}
        out += [f"## File system: {title}", "",
                f"{m['operations']} commands: {m['succeeded']} succeeded, {m['failed']} safe errors, {m['denied']} denied; {m['bytes_written']} B written, "
                f"{m['bytes_read']} B read; {m['dirs_created']} directories and {m['files_created']} files created, {m['dirs_deleted']} and {m['files_deleted']} deleted; "
                f"{m['storage_used']} B stored at the end; average latency {m['avg_latency']:.2f} ms.", "",
                "| Command | Count | ok | error | denied | Total latency (ms) | Average (ms) |", "| --- | --- | --- | --- | --- | --- | --- |"]
        for c, v in fm.per_command().items():
            out.append(f"| {c} | {v['count']} | {v['ok']} | {v['failed']} | {v['denied']} | {v['total_ticks'] / 10:.1f} | {v['avg_ms']:.2f} |")
        out.append("")
    (ROOT / "docs" / "m3_results.md").write_text("\n".join(out))
    try:
        import matplotlib
        matplotlib.use("Agg")
        import matplotlib.pyplot as plt
    except ImportError:
        print("matplotlib not installed: tables written, figure skipped")
        return
    labels = ["Baseline", "Locality"]
    fifo = [r[2] for r in mem if r[1] == "FIFO"]
    lru = [r[2] for r in mem if r[1] == "LRU"]
    fig, axes = plt.subplots(1, 2, figsize=(9, 3.6))
    for ax, key, title, unit in ((axes[0], "faults", "Page faults", "faults"), (axes[1], "avg_access_time", "Average access time", "ms")):
        xs = range(len(labels))
        a = ax.bar([x - 0.2 for x in xs], [m[key] for m in fifo], 0.4, label="FIFO", color="#2f6fdb")
        b = ax.bar([x + 0.2 for x in xs], [m[key] for m in lru], 0.4, label="LRU", color="#1d9e74", hatch="//")
        ax.bar_label(a, fmt="%g", padding=2)
        ax.bar_label(b, fmt="%g", padding=2)
        ax.set_xticks(list(xs), labels)
        ax.set_ylabel(unit)
        ax.set_title(f"{title}, FIFO vs LRU")
        ax.spines[["top", "right"]].set_visible(False)
        ax.legend(frameon=False)
    fig.suptitle("Same trace for both policies: 4096-byte pages, 3 frames, hit 0.1 ms, fault 5.0 ms", fontsize=9)
    fig.tight_layout()
    fig.savefig(ROOT / "docs" / "figures" / "m3_fifo_vs_lru.png", dpi=150)


if __name__ == "__main__":
    main()
